/** Sing-along timing: start seconds per stanza and per line (see lib/read-along). */
const timingSchema = z.object({
  stanzas: z.array(z.number().nonnegative()),
  lines: z.array(z.array(z.number().nonnegative())),
  /** Start seconds per word of a line the aligner heard; null lights the line whole. */
  words: z
    .array(z.array(z.array(z.number().nonnegative()).nullable()))
    .optional(),
})

const trackSchema = z.object({
  id: trackIdSchema,
  title: z.string(),
  /** Short dedication for the album card. */
  dedication: z.string(),
  /** The day it was written, ISO YYYY-MM-DD; the timeline and the lyrics header read it. */
  written: z.string().regex(/^\d{4}-\d{2}-\d{2}$/),
  voice: z.string(),
  /** BCP 47 tag of the words, for screen readers and hyphenation. */
  lang: z.enum(['en', 'fr']).default('en'),
  description: z.string(),
  audioFile: z.string(),
  /** Fallback length in seconds until the element reports metadata. */
  duration: z.number().positive(),
  art: z.object({ full: z.string(), thumb: z.string() }),
  /** Browser chrome color while this track is showing. */
  themeColor: z.string(),
  driveLink: z.url().optional(),
  /**
   * Stanzas of lines from src/data/lyrics/<id>.json. A line wrapped in
   * [brackets] is a label (a section or a voice) and renders small, not sung.
   */
  lyrics: z.array(z.array(z.string()).min(1)),
  /** Whether the words came from a sheet or were transcribed from the recording. */
  lyricsSource: z.enum(['sheet', 'transcribed']),
  /** Generated by the align script from Whisper word timestamps; absent means read by scroll. */
  timing: timingSchema.optional(),
})
export type Track = z.infer<typeof trackSchema>

// timing.json is regenerated by the align script; songs it lacks read by scroll.
const timingFor = (id: TrackId) => (timingData as Record<string, unknown>)[id]

