export function adjacentTrack(id: TrackId, direction: 1 | -1): TrackId {
  const i = TRACK_ORDER.indexOf(id)
  return TRACK_ORDER[(i + direction + TRACK_ORDER.length) % TRACK_ORDER.length]
}

export function isLastTrack(id: TrackId) {
  return TRACK_ORDER.indexOf(id) === TRACK_ORDER.length - 1
}

/** A line wrapped in [brackets] is a section or voice label, not sung. */
export function isLyricLabel(line: string) {
  return line.startsWith('[') && line.endsWith(']')
}

type Lyrics = ReadonlyArray<ReadonlyArray<string>>

/** True when two sheets line up stanza for stanza and line for line, like the mirrored pair. */
export function sameLyricShape(a: Lyrics, b: Lyrics) {
  return a.length === b.length && a.every((s, i) => s.length === b[i].length)
}

/** "March 2, 2026": the day it was written, spelled out. */
export function writtenDate(t: Track) {
  return new Date(`${t.written}T12:00:00`).toLocaleDateString('en-US', {
    month: 'long',
    day: 'numeric',
    year: 'numeric',
  })
}

/** "For Alex, from Dustin — March 2, 2026": the dedication with the date, for the action sheet. */
export function dedicationLine(t: Track) {
  return `${t.dedication} — ${writtenDate(t)}`
}

/** "Fire & Water", "Not Afraid to Change": the title without its parenthetical, for tight spots. */
export function shortTitle(id: TrackId) {
  return TRACKS[id].title.replace(' and ', ' & ').replace(/\s*\(.*\)$/, '')
}
